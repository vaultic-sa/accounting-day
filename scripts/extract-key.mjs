// Builds supabase answer-key SQL from the ROUNDS array in index.html (single source of truth).
import {readFileSync} from "node:fs";
const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
const src=html.slice(html.indexOf("const J="),html.indexOf("const MAX_LIVES"));
const ROUNDS=new Function(src+";return ROUNDS")();
const q=s=>"'"+String(s).replace(/'/g,"''")+"'";
const rows=[];
ROUNDS.forEach((r,ri)=>r.qs.forEach((x,qi)=>{
  if(x.o) rows.push(`(${ri},${qi},'opt',${x.o.findIndex(o=>o.ok)},null,null)`);
  else if(x.w) rows.push(`(${ri},${qi},'word',null,${q(x.w)},null)`);
  else rows.push(`(${ri},${qi},'amount',null,null,${x.ans})`);
}));
console.log(`-- generated by scripts/extract-key.mjs from index.html (${rows.length} questions)`);
console.log(`truncate public.answer_key;\ninsert into public.answer_key(r,qi,kind,correct_opt,word,amount) values\n${rows.join(",\n")};`);
console.error(ROUNDS.map((r,i)=>`${i}:${r.key}:${r.qs.length}:${r.time||0}`).join(" "));
